export type IconProps = Omit<SVGProps<SVGSVGElement>, "ref"> & {
  size?: number | string;
  strokeWidth?: number | string;
  absoluteStrokeWidth?: boolean;
};
export type IosIcon = ComponentType<IconProps>;
/** lucide-react'dagi LucideIcon o'rniga. */
export type LucideIcon = IosIcon;

function wrap(Raw: ComponentType<SVGProps<SVGSVGElement>>, name: string): IosIcon {
  // eslint-disable-next-line @typescript-eslint/no-unused-vars -- lucide-only props are dropped
  function Icon({ size = 24, strokeWidth: _s, absoluteStrokeWidth: _a, fill: _f, ...rest }: IconProps) {
    return <Raw width={size} height={size} aria-hidden={rest["aria-label"] ? undefined : true} focusable="false" {...rest} />;
  }
  Icon.displayName = name;
  return Icon;
}

